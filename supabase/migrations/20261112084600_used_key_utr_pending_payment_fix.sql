create table if not exists private.used_key_payment_utr_function_backup (
  id bigint generated by default as identity primary key,
  migration_name text not null,
  captured_at timestamptz not null default clock_timestamp(),
  captured_by uuid,
  function_definition text not null
);

revoke all on table private.used_key_payment_utr_function_backup
  from public, anon, authenticated;

do $migration$
declare
  v_function regprocedure := 'public.submit_product_payment_utr(bigint,text)'::regprocedure;
  v_definition text;
  v_updated_definition text;
  v_pattern text := $pattern$and\s+status\s+in\s*\(\s*'unpaid'\s*,\s*'expired'\s*\)\s+and\s+utr\s+is\s+null\s+and\s+offer_claim_id\s+is\s+null$pattern$;
  v_match_count integer;
begin
  v_definition := pg_get_functiondef(v_function);

  select count(*) into v_match_count
  from regexp_matches(v_definition, v_pattern, 'gi');

  if v_match_count <> 1 then
    raise exception
      'Expected exactly one known UTR eligibility predicate in %, found %. No function was changed.',
      v_function, v_match_count;
  end if;

  insert into private.used_key_payment_utr_function_backup (
    migration_name, captured_by, function_definition
  ) values (
    '20261112084600_used_key_utr_pending_payment_fix',
    auth.uid(),
    v_definition
  );

  v_updated_definition := regexp_replace(
    v_definition,
    v_pattern,
    $replacement$AND (
        status IN ('unpaid', 'expired')
        OR (
          used_key_id IS NOT NULL
          AND status = 'pending_payment'
          AND payment_expires_at IS NOT NULL
        )
      )
      AND utr IS NULL
      AND offer_claim_id IS NULL$replacement$,
    'i'
  );

  execute v_updated_definition;
end;
$migration$;

create table if not exists private.used_key_payment_recovery_audit (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id),
  used_key_id bigint not null references private.used_key_inventory(id),
  actor_id uuid not null references auth.users(id),
  utr text not null check (utr ~ '^[0-9]{12}$'),
  verified_amount numeric(12, 2) not null,
  previous_status text not null,
  reason text not null check (length(btrim(reason)) between 3 and 1000),
  created_at timestamptz not null default clock_timestamp()
);

revoke all on table private.used_key_payment_recovery_audit
  from public, anon, authenticated;

create or replace function public.admin_recover_ocean_pro_used_key_payment_utr(
  p_order_id bigint,
  p_used_key_id bigint,
  p_utr text,
  p_expected_key text,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_order public.orders%rowtype;
  v_key private.used_key_inventory%rowtype;
  v_encryption_key text;
  v_verified_amount constant numeric(12, 2) := 399.00;
  v_utr text := btrim(coalesce(p_utr, ''));
  v_now timestamptz := clock_timestamp();
  v_late boolean;
  v_claim_rows integer;
  v_audit_id bigint;
begin
  if auth.uid() is null or not coalesce(public.is_store_admin(), false) then
    raise exception 'Admin access required';
  end if;

  if length(btrim(coalesce(p_reason, ''))) not between 3 and 1000 then
    raise exception 'Provide an audit reason between 3 and 1000 characters.';
  end if;
  if v_utr !~ '^[0-9]{12}$' then
    raise exception 'Enter a valid 12-digit UTR.';
  end if;
  if length(btrim(coalesce(p_expected_key, ''))) = 0 then
    raise exception 'Expected Used Key is required.';
  end if;

  select * into v_order
  from public.orders
  where id = p_order_id
  for update;

  if not found then
    raise exception 'Order not found.';
  end if;

  if v_order.used_key_id is null
     or v_order.used_key_id <> p_used_key_id
     or v_order.product_type is distinct from 'software'
     or upper(btrim(coalesce(v_order.product_name, ''))) <> 'OCEAN PRO'
     or v_order.payment_method is distinct from 'upi_qr'
     or v_order.status not in ('pending_payment', 'expired')
     or v_order.utr is not null
     or v_order.utr_number is not null
     or v_order.payment_expires_at is null
     or v_order.price is distinct from v_verified_amount
     or v_order.amount is distinct from v_verified_amount then
    raise exception
      'Order is not the expected unsubmitted OCEAN PRO Used Key payment for ₹399.';
  end if;

  select * into v_key
  from private.used_key_inventory
  where id = v_order.used_key_id
  for update;

  if not found
     or v_key.status is distinct from 'available'
     or not coalesce(v_key.is_visible, false)
     or v_key.reserved_order_id is not null
     or v_key.product_id <> v_order.product_id
     or v_key.license_key_fingerprint is distinct from v_order.used_key_fingerprint then
    raise exception 'Used Key is reserved, unavailable, or no longer matches this order.';
  end if;

  select encryption_key into v_encryption_key
  from private.order_delivery_secrets
  where id = true;

  if v_encryption_key is null
     or v_key.license_key_fingerprint is distinct from
       extensions.hmac(btrim(p_expected_key), v_encryption_key, 'sha256') then
    raise exception 'Used Key does not match the supplied expected key.';
  end if;

  if exists (
       select 1 from public.payment_utr_claims
       where utr_normalized = lower(v_utr)
     )
     or exists (
       select 1 from public.topup_requests
       where lower(utr) = lower(v_utr)
     )
     or exists (
       select 1 from public.orders
       where lower(coalesce(utr, '')) = lower(v_utr)
          or lower(coalesce(utr_number, '')) = lower(v_utr)
     ) then
    raise exception 'This UTR has already been submitted.';
  end if;

  insert into public.payment_utr_claims (utr_normalized, source)
  values (lower(v_utr), 'product_order')
  on conflict do nothing;

  get diagnostics v_claim_rows = row_count;
  if v_claim_rows <> 1 then
    raise exception 'Could not reserve this UTR; check for a duplicate.';
  end if;

  v_late := v_order.status = 'expired'
    or v_now > v_order.payment_expires_at;

  update public.orders
  set utr = v_utr,
      utr_number = v_utr,
      utr_submitted_at = v_now,
      payment_submitted_at = v_now,
      late_payment = v_late,
      status = 'new',
      payment_status = 'pending'
  where id = v_order.id;

  insert into private.used_key_payment_recovery_audit (
    order_id, used_key_id, actor_id, utr, verified_amount, previous_status, reason
  ) values (
    v_order.id, v_order.used_key_id, auth.uid(), v_utr, v_verified_amount,
    v_order.status, btrim(p_reason)
  )
  returning id into v_audit_id;

  return jsonb_build_object(
    'ok', true,
    'order_id', v_order.id,
    'status', 'new',
    'late_payment', v_late,
    'audit_id', v_audit_id
  );
end;
$function$;

revoke all on function public.admin_recover_ocean_pro_used_key_payment_utr(bigint, bigint, text, text, text)
  from public, anon, authenticated;
grant execute on function public.admin_recover_ocean_pro_used_key_payment_utr(bigint, bigint, text, text, text)
  to authenticated;

commit;
