create or replace function public.validate_offer()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.title is null or length(btrim(new.title)) not between 1 and 120 then
    raise exception 'Offer title must be between 1 and 120 characters';
  end if;
  if new.description is null or length(new.description) > 500 then
    raise exception 'Offer description cannot exceed 500 characters';
  end if;
  if new.collection is null or new.collection not in ('software', 'vps', 'proxy', 'residential') then
    raise exception 'Offer collection is invalid';
  end if;
  if new.starts_at is null or new.ends_at is null or new.ends_at <= new.starts_at then
    raise exception 'Offer start and end times are required and the end must be after the start';
  end if;
  if new.product_id is not null and not exists (
    select 1 from public.products p
    where p.id = new.product_id and p.category = new.collection
  ) then
    raise exception 'Selected product must belong to the chosen collection';
  end if;
  if new.paid_quantity not between 1 and 100 or new.free_quantity not between 1 and 100
     or new.benefit_count < 0 or new.benefit_count_minimum not between 1 and 100000000 then
    raise exception 'Offer quantities or benefit-count settings are invalid';
  end if;
  if new.claim_enabled and new.collection <> 'software' then
    raise exception 'Claim and free-software offers must use the Software collection';
  end if;
  new.updated_at = now();
  return new;
end;
$$;
revoke all on function public.validate_offer() from public, anon, authenticated;

