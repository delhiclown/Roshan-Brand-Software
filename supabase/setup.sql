create or replace function public.admin_adjust_wallet(p_user_id uuid, p_type text, p_amount numeric, p_note text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_balance numeric(12, 2);
begin
  if not public.is_store_admin() then raise exception 'Admin access required'; end if;
  if p_type not in ('admin_credit', 'admin_debit') or p_amount <= 0 or p_amount > 10000000 then
    return jsonb_build_object('ok', false, 'message', 'Enter a valid adjustment amount and type.');
  end if;
  if length(trim(coalesce(p_note, ''))) < 2 or length(trim(p_note)) > 240 then
    return jsonb_build_object('ok', false, 'message', 'Enter a note between 2 and 240 characters.');
  end if;
  insert into public.wallets (user_id) values (p_user_id) on conflict (user_id) do nothing;
  select balance into v_balance from public.wallets where user_id = p_user_id for update;
  if p_type = 'admin_debit' and v_balance < p_amount then
    return jsonb_build_object('ok', false, 'message', 'Deduction exceeds the available wallet balance.', 'balance', v_balance);
  end if;
  update public.wallets set balance = balance + case when p_type = 'admin_credit' then p_amount else -p_amount end, updated_at = now()
    where user_id = p_user_id returning balance into v_balance;
  insert into public.wallet_transactions (user_id, type, amount, note)
    values (p_user_id, p_type, p_amount, trim(p_note));
  return jsonb_build_object('ok', true, 'balance', v_balance);
end;
$$;

