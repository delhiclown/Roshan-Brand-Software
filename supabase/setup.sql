create or replace function public.purchase_product(p_product_id bigint, p_expected_price numeric)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_balance numeric(12, 2);
  v_download_url text;
  v_product public.products%rowtype;
  v_order public.orders%rowtype;
begin
  if v_user_id is null then raise exception 'Sign in required'; end if;
  if not coalesce((select enable_wallet_payments from public.settings where id = true), false) then
    return jsonb_build_object('ok', false, 'reason', 'payment_disabled', 'message', 'Wallet payments are currently unavailable.');
  end if;
  insert into public.wallets (user_id) values (v_user_id) on conflict (user_id) do nothing;
  select balance into v_balance from public.wallets where user_id = v_user_id for update;
  select * into v_product from public.products where id = p_product_id and in_stock = true for share;
  if not found then return jsonb_build_object('ok', false, 'reason', 'unavailable', 'message', 'Product is unavailable.'); end if;
  if v_product.price <> p_expected_price then
    return jsonb_build_object('ok', false, 'reason', 'price_changed', 'price', v_product.price);
  end if;
  if v_balance < v_product.price then
    return jsonb_build_object('ok', false, 'reason', 'insufficient_balance', 'balance', v_balance);
  end if;
  select download_url into v_download_url
    from public.product_download_links where product_id = v_product.id;
  update public.wallets set balance = balance - v_product.price, updated_at = now()
    where user_id = v_user_id returning balance into v_balance;
  insert into public.orders (
    user_id, product_id, product_name, product_type, price, status, delivery_link, delivered_at
  )
    values (
      v_user_id, v_product.id, v_product.name, v_product.category, v_product.price,
      case when v_download_url is null then 'pending' else 'delivered' end,
      v_download_url,
      case when v_download_url is null then null else now() end
    )
    returning * into v_order;
  insert into public.wallet_transactions (user_id, type, amount, note, order_id)
    values (v_user_id, 'purchase', v_product.price, 'Purchase: ' || v_product.name, v_order.id);
  return jsonb_build_object('ok', true, 'order_id', v_order.id, 'product_name', v_order.product_name,
    'price', v_order.price, 'product_type', v_order.product_type,
    'balance', v_balance, 'created_at', v_order.created_at,
    'download_ready', v_order.status = 'delivered');
end;
$$;

create or replace function public.create_topup_request(p_amount numeric, p_utr text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_request public.topup_requests%rowtype;
  v_utr text := lower(trim(coalesce(p_utr, '')));
begin
  if v_user_id is null then raise exception 'Sign in required'; end if;
  if not coalesce((
    select (enable_upi_qr or enable_upi_app)
      and length(trim(upi_id)) > 0 and length(trim(upi_payee_name)) > 0
    from public.settings where id = true
  ), false) then
    return jsonb_build_object('ok', false, 'message', 'UPI payments are currently unavailable.');
  end if;
  if p_amount < 10 or p_amount > 100000 or p_amount <> trunc(p_amount) then
    return jsonb_build_object('ok', false, 'message', 'Top-up amount must be a whole number between 10 and 100000.');
  end if;
  if length(trim(coalesce(p_utr, ''))) < 6 or length(trim(p_utr)) > 64 then
    return jsonb_build_object('ok', false, 'message', 'Enter a valid UTR / transaction ID.');
  end if;
  if exists (select 1 from public.topup_requests where lower(utr) = v_utr)
     or exists (select 1 from public.orders where lower(utr) = v_utr) then
    return jsonb_build_object('ok', false, 'message', 'This UTR has already been submitted.');
  end if;
  insert into public.payment_utr_claims (utr_normalized, source)
    values (v_utr, 'topup') on conflict do nothing;
  if not found then return jsonb_build_object('ok', false, 'message', 'This UTR has already been submitted.'); end if;
  insert into public.topup_requests (user_id, amount, utr)
    values (v_user_id, p_amount, trim(p_utr)) returning * into v_request;
  return jsonb_build_object('ok', true, 'request_id', v_request.id, 'status', v_request.status);
end;
$$;

create or replace function public.create_upi_product_order(
  p_product_id bigint, p_expected_price numeric, p_original_price numeric,
  p_discount_percent numeric, p_coupon_code text, p_payment_method text, p_utr text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_product public.products%rowtype;
  v_order public.orders%rowtype;
  v_utr text := lower(trim(coalesce(p_utr, '')));
  v_coupon text := upper(nullif(trim(coalesce(p_coupon_code, '')), ''));
begin
  if v_user_id is null then raise exception 'Sign in required'; end if;
  if p_payment_method not in ('upi_qr', 'upi_app') then
    return jsonb_build_object('ok', false, 'message', 'Choose a supported UPI payment method.');
  end if;
  if not coalesce((
    select case p_payment_method
      when 'upi_qr' then enable_upi_qr
      when 'upi_app' then enable_upi_app
      else false
    end
      and length(trim(upi_id)) > 0 and length(trim(upi_payee_name)) > 0
    from public.settings where id = true
  ), false) then
    return jsonb_build_object('ok', false, 'message', 'This payment method is currently unavailable.');
  end if;
  if p_utr !~ '^[0-9]{12}$' then
    return jsonb_build_object('ok', false, 'message', 'Enter a valid 12-digit UTR / transaction ID.');
  end if;
  if v_coupon is not null and v_coupon !~ '^RB(100|[1-9][0-9]?)-[A-HJ-NP-Z2-9]{8}$' then
    return jsonb_build_object('ok', false, 'message', 'Coupon code format is invalid.');
  end if;
