create or replace function public.purchase_product(p_product_id bigint, p_expected_price numeric)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_balance numeric(12, 2);
  v_download_url text;
  v_product public.products%rowtype;
  v_order public.orders%rowtype;
begin
  if v_user_id is null then raise exception 'Sign in required'; end if;
  insert into public.wallets (user_id) values (v_user_id) on conflict (user_id) do nothing;
  select balance into v_balance from public.wallets where user_id = v_user_id for update;
  select * into v_product from public.products where id = p_product_id and in_stock = true for share;
  if not found then return jsonb_build_object('ok', false, 'reason', 'unavailable', 'message', 'Product is unavailable.'); end if;
  if v_product.price <> p_expected_price then
    return jsonb_build_object('ok', false, 'reason', 'price_changed', 'price', v_product.price);
  end if;
  if v_balance < v_product.price then
    return jsonb_build_object('ok', false, 'reason', 'insufficient_balance', 'balance', v_balance);
  end if;
  select download_url into v_download_url
    from public.product_download_links where product_id = v_product.id;
  update public.wallets set balance = balance - v_product.price, updated_at = now()
    where user_id = v_user_id returning balance into v_balance;
  insert into public.orders (
    user_id, product_id, product_name, product_type, price, status, delivery_link, delivered_at
  )
    values (
      v_user_id, v_product.id, v_product.name, v_product.category, v_product.price,
      case when v_download_url is null then 'pending' else 'delivered' end,
      v_download_url,
      case when v_download_url is null then null else now() end
    )
    returning * into v_order;
  insert into public.wallet_transactions (user_id, type, amount, note, order_id)
    values (v_user_id, 'purchase', v_product.price, 'Purchase: ' || v_product.name, v_order.id);
  return jsonb_build_object('ok', true, 'order_id', v_order.id, 'product_name', v_order.product_name,
    'price', v_order.price, 'product_type', v_order.product_type,
    'balance', v_balance, 'created_at', v_order.created_at,
    'download_ready', v_order.status = 'delivered');
end;
$$;

create or replace function public.create_topup_request(p_amount numeric, p_utr text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_request public.topup_requests%rowtype;
begin
  if v_user_id is null then raise exception 'Sign in required'; end if;
  if p_amount < 10 or p_amount > 100000 or p_amount <> trunc(p_amount) then
    return jsonb_build_object('ok', false, 'message', 'Top-up amount must be a whole number between 10 and 100000.');
  end if;
  if length(trim(coalesce(p_utr, ''))) < 6 or length(trim(p_utr)) > 64 then
    return jsonb_build_object('ok', false, 'message', 'Enter a valid UTR / transaction ID.');
  end if;
  if exists (select 1 from public.topup_requests where lower(utr) = lower(trim(p_utr))) then
    return jsonb_build_object('ok', false, 'message', 'This UTR has already been submitted.');
  end if;
  insert into public.topup_requests (user_id, amount, utr) values (v_user_id, p_amount, trim(p_utr)) returning * into v_request;
  return jsonb_build_object('ok', true, 'request_id', v_request.id, 'status', v_request.status);
end;
$$;

create or replace function public.admin_review_topup(p_request_id bigint, p_approve boolean)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_request public.topup_requests%rowtype;
  v_balance numeric(12, 2);
  v_admin uuid := auth.uid();
begin
  if not public.is_store_admin() then raise exception 'Admin access required'; end if;
  select * into v_request from public.topup_requests where id = p_request_id for update;
  if not found then return jsonb_build_object('ok', false, 'message', 'Top-up request not found.'); end if;
  if v_request.status <> 'pending' then return jsonb_build_object('ok', false, 'message', 'This request has already been reviewed.'); end if;
  if p_approve then
    insert into public.wallets (user_id) values (v_request.user_id) on conflict (user_id) do nothing;
    select balance into v_balance from public.wallets where user_id = v_request.user_id for update;
    update public.wallets set balance = balance + v_request.amount, updated_at = now()
      where user_id = v_request.user_id returning balance into v_balance;
    update public.topup_requests set status = 'approved', reviewed_at = now(), reviewed_by = v_admin where id = v_request.id;
    insert into public.wallet_transactions (user_id, type, amount, note)
      values (v_request.user_id, 'topup', v_request.amount, 'Top-up approved · UTR ' || v_request.utr);
    return jsonb_build_object('ok', true, 'status', 'approved', 'balance', v_balance);
  end if;
  update public.topup_requests set status = 'rejected', reviewed_at = now(), reviewed_by = v_admin where id = v_request.id;
  return jsonb_build_object('ok', true, 'status', 'rejected');
end;
$$;

create or replace function public.admin_refund_order(p_order_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order public.orders%rowtype;
  v_balance numeric(12, 2);
begin
  if not public.is_store_admin() then raise exception 'Admin access required'; end if;
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then return jsonb_build_object('ok', false, 'message', 'Order not found.'); end if;
  if v_order.status = 'refunded' then return jsonb_build_object('ok', false, 'message', 'This order has already been refunded.'); end if;
  insert into public.wallets (user_id) values (v_order.user_id) on conflict (user_id) do nothing;
  select balance into v_balance from public.wallets where user_id = v_order.user_id for update;
  update public.wallets set balance = balance + v_order.price, updated_at = now()
    where user_id = v_order.user_id returning balance into v_balance;
  update public.orders set status = 'refunded' where id = v_order.id;
  insert into public.wallet_transactions (user_id, type, amount, note, order_id)
    values (v_order.user_id, 'refund', v_order.price, 'Refund: ' || v_order.product_name, v_order.id);
