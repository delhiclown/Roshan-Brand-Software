create or replace function public.admin_review_offer_claim(
  p_claim_id uuid, p_approve boolean, p_reason text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_claim public.offer_claims%rowtype;
  v_product public.products%rowtype;
  v_order_id bigint;
  v_total numeric(12,2);
  v_reason text := trim(coalesce(p_reason,''));
begin
  if not public.is_store_admin() then raise exception 'Admin access required'; end if;
  if p_approve is null then
    return jsonb_build_object('ok',false,'message','Choose whether to approve or reject this claim.');
  end if;
  if not p_approve and (length(v_reason)<1 or length(v_reason)>1000) then
    return jsonb_build_object('ok',false,'message','Enter a rejection reason of 1–1000 characters.');
  end if;
  select * into v_claim from public.offer_claims where id=p_claim_id for update;
  if not found or v_claim.status<>'pending' then
    return jsonb_build_object('ok',false,'message','This claim is no longer waiting for review.');
  end if;
  if p_approve then
    select * into v_product from public.products
      where id=v_claim.product_id and category='software' and in_stock=true for share;
    if not found then return jsonb_build_object('ok',false,'message','The claimed software is no longer available.'); end if;
    if not coalesce((select enable_upi_qr and length(trim(upi_id))>0 and length(trim(upi_payee_name))>0
      from public.settings where id=true),false) then
      return jsonb_build_object('ok',false,'message','Configure and enable UPI QR payments before approving claims.');
    end if;
    v_total := round(v_claim.unit_price*v_claim.paid_quantity,2);
    insert into public.orders(
      user_id,product_id,product_name,product_type,price,original_price,status,payment_method,
      payment_status,quantity,offer_id,offer_claim_id,expires_at
    ) values (
      v_claim.user_id,v_claim.product_id,v_claim.product_name,'software',v_total,v_total,
      'pending_payment','upi_qr','pending',v_claim.paid_quantity,v_claim.offer_id,v_claim.id,
      now()+interval '24 hours'
    ) returning id into v_order_id;
    update public.offer_claims set status='approved',payment_order_id=v_order_id,
      rejection_reason=null,reviewed_at=now(),reviewed_by=auth.uid()
      where id=v_claim.id;
    insert into public.offer_audit_events(actor_id,action,offer_id,claim_id,order_id,details)
      values(auth.uid(),'claim_approved',v_claim.offer_id,v_claim.id,v_order_id,
        jsonb_build_object('paid_quantity',v_claim.paid_quantity,'amount',v_total));
    return jsonb_build_object('ok',true,'status','approved','order_id',v_order_id,'amount',v_total);
  end if;
  update public.offer_claims set status='rejected',rejection_reason=v_reason,
    name_enabled=false,reviewed_at=now(),reviewed_by=auth.uid() where id=v_claim.id;
  insert into public.offer_audit_events(actor_id,action,offer_id,claim_id,details)
    values(auth.uid(),'claim_rejected',v_claim.offer_id,v_claim.id,jsonb_build_object('reason',v_reason));
  return jsonb_build_object('ok',true,'status','rejected');
end;
$$;

create or replace function public.submit_offer_order_payment(p_order_id bigint,p_utr text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order public.orders%rowtype;
  v_utr text := lower(trim(coalesce(p_utr,'')));
begin
  if auth.uid() is null then raise exception 'Sign in required'; end if;
  if v_utr !~ '^[0-9]{12}$' then
    return jsonb_build_object('ok',false,'message','Enter a valid 12-digit UTR / transaction ID.');
  end if;
  select * into v_order from public.orders
    where id=p_order_id and user_id=auth.uid() and offer_claim_id is not null
    for update;
  if not found or v_order.status<>'pending_payment' or v_order.payment_status<>'pending' then
    return jsonb_build_object('ok',false,'message','This offer order is not awaiting payment.');
  end if;
  if v_order.expires_at is null or v_order.expires_at<=now() then
    return jsonb_build_object('ok',false,'message','This offer order has expired.');
  end if;
  if not coalesce((select enable_upi_qr from public.settings where id=true),false) then
    return jsonb_build_object('ok',false,'message','UPI QR payments are currently unavailable.');
  end if;
  if exists(select 1 from public.payment_utr_claims where utr_normalized=v_utr)
     or exists(select 1 from public.topup_requests where lower(utr)=v_utr)
     or exists(select 1 from public.orders where lower(utr)=v_utr) then
    return jsonb_build_object('ok',false,'message','This UTR has already been submitted.');
  end if;
  insert into public.payment_utr_claims(utr_normalized,source)
    values(v_utr,'offer_product_order') on conflict do nothing;
  if not found then return jsonb_build_object('ok',false,'message','This UTR has already been submitted.'); end if;
  update public.orders set utr=trim(p_utr),status='pending_verification'
    where id=v_order.id;
  insert into public.offer_audit_events(actor_id,action,offer_id,claim_id,order_id,details)
    values(auth.uid(),'offer_payment_submitted',v_order.offer_id,v_order.offer_claim_id,v_order.id,'{}'::jsonb);
  return jsonb_build_object('ok',true,'status','pending_verification');
end;
$$;

