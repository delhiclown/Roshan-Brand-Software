create or replace function public.expire_offer_requests()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_count integer := 0;
  v_updated integer;
begin
  update public.offer_claims set status='expired',name_enabled=false
    where status in ('pending','rejected') and updated_at<=now()-interval '24 hours';
  get diagnostics v_updated=row_count;
  v_count := v_count+v_updated;
  update public.orders set status='expired',payment_status='rejected',
    reject_reason='Payment window expired after 24 hours.'
    where offer_claim_id is not null and status='pending_payment'
      and payment_status='pending' and expires_at<=now();
  get diagnostics v_updated=row_count;
  v_count := v_count+v_updated;
  update public.offer_claims c set status='expired',name_enabled=false
    from public.orders o where c.payment_order_id=o.id and c.status='approved'
      and o.status='expired';
  get diagnostics v_updated=row_count;
  v_count := v_count+v_updated;
  return v_count;
end;
$$;

