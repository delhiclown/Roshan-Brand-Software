do $$
begin
  if exists(select 1 from pg_available_extensions where name='pg_cron') then
    execute 'create extension if not exists pg_cron';
    if exists(select 1 from cron.job where jobname='expire-offer-claims') then
      execute 'select cron.unschedule(''expire-offer-claims'')';
    end if;
    execute $schedule$
      select cron.schedule(
        'expire-offer-claims',
        '*/5 * * * *',
        'select public.expire_offer_requests()'
      )
    $schedule$;
  else
    raise notice 'pg_cron is not available; offer claim expiry must be scheduled in Supabase before launch.';
  end if;
end
$$;

