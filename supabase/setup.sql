create or replace function public.submit_offer_claim(
  p_offer_id uuid, p_product_id bigint, p_screenshot_base64 text,
  p_screenshot_mime text, p_share_name boolean
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_offer public.offers%rowtype;
  v_product public.products%rowtype;
  v_claim public.offer_claims%rowtype;
  v_existing boolean := false;
  v_bytes bytea;
  v_hash text;
  v_name text;
begin
  if v_user_id is null then raise exception 'Sign in required'; end if;
  if p_screenshot_base64 is null or length(p_screenshot_base64)>2800000 then
    return jsonb_build_object('ok',false,'message','Screenshot must be 2 MB or smaller.');
  end if;
  if p_screenshot_mime is null or p_screenshot_mime not in ('image/png','image/jpeg','image/webp') then
    return jsonb_build_object('ok',false,'message','Upload a PNG, JPG, or WebP screenshot.');
  end if;
  v_bytes := decode(p_screenshot_base64,'base64');
  if octet_length(v_bytes)=0 or octet_length(v_bytes)>2097152 then
    return jsonb_build_object('ok',false,'message','Screenshot must be 2 MB or smaller.');
  end if;
  if (p_screenshot_mime='image/png' and substring(v_bytes from 1 for 8)<>decode('89504e470d0a1a0a','hex'))
     or (p_screenshot_mime='image/jpeg' and substring(v_bytes from 1 for 3)<>decode('ffd8ff','hex'))
     or (p_screenshot_mime='image/webp' and
       (substring(v_bytes from 1 for 4)<>convert_to('RIFF','UTF8')
        or substring(v_bytes from 9 for 4)<>convert_to('WEBP','UTF8'))) then
    return jsonb_build_object('ok',false,'message','The screenshot content does not match its file type.');
  end if;
  select * into v_offer from public.offers
    where id=p_offer_id and claim_enabled and collection='software'
    for share;
  if not found then return jsonb_build_object('ok',false,'message','This offer does not accept claims.'); end if;
  select * into v_product from public.products
    where id=p_product_id and category='software' and in_stock=true
    for share;
  if not found or (v_offer.product_id is not null and v_offer.product_id<>p_product_id) then
    return jsonb_build_object('ok',false,'message','Choose an available software product for this offer.');
  end if;
  select * into v_claim from public.offer_claims
    where offer_id=p_offer_id and user_id=v_user_id for update;
  v_existing := found;
  if v_existing then
    if v_claim.status<>'rejected' then
      return jsonb_build_object('ok',false,'message','You have already claimed this offer.');
    end if;
    if not v_offer.enabled or v_offer.starts_at>now() or v_offer.ends_at<=now()
       or p_product_id<>v_claim.product_id or v_claim.created_at<v_offer.starts_at
       or v_claim.created_at>v_offer.ends_at or v_claim.updated_at<now()-interval '24 hours' then
      return jsonb_build_object('ok',false,'message','The rejected claim can no longer be resubmitted.');
    end if;
  elsif not v_offer.enabled or v_offer.starts_at>now() or v_offer.ends_at<=now() then
    return jsonb_build_object('ok',false,'message','This offer is not currently active.');
  end if;
  v_hash := encode(extensions.digest(v_bytes,'sha256'),'hex');
  if not v_existing then
    select coalesce(nullif(u.raw_user_meta_data->>'full_name',''),
      nullif(u.raw_user_meta_data->>'name',''),nullif(split_part(u.email::text,'@',1),''),'Customer')
      into v_name from auth.users u where u.id=v_user_id;
    insert into public.offer_claims(
      offer_id,user_id,product_id,product_name,paid_quantity,free_quantity,unit_price,
      screenshot_bytes,screenshot_mime,display_name,share_name,name_enabled
    ) values (
      p_offer_id,v_user_id,v_product.id,v_product.name,v_offer.paid_quantity,v_offer.free_quantity,v_product.price,
      v_bytes,p_screenshot_mime,coalesce(v_name,'Customer'),coalesce(p_share_name,false),coalesce(p_share_name,false)
    ) returning * into v_claim;
  end if;
  insert into public.offer_claim_screenshot_hashes(screenshot_sha256,claim_id)
    values(v_hash,v_claim.id) on conflict(screenshot_sha256) do nothing;
  if not found then
    if not v_existing then delete from public.offer_claims where id=v_claim.id; end if;
    return jsonb_build_object('ok',false,'message','This screenshot has already been used.');
  end if;
  if v_existing then
    update public.offer_claims set screenshot_bytes=v_bytes,screenshot_mime=p_screenshot_mime,
      status='pending',rejection_reason=null,reviewed_at=null,reviewed_by=null,
      share_name=coalesce(p_share_name,false),name_enabled=coalesce(p_share_name,false)
      where id=v_claim.id;
  end if;
  insert into public.offer_audit_events(actor_id,action,offer_id,claim_id,details)
    values(v_user_id,'claim_submitted',p_offer_id,v_claim.id,jsonb_build_object('resubmission',v_existing));
  return jsonb_build_object('ok',true,'claim_id',v_claim.id,'status','pending');
end;
$$;

