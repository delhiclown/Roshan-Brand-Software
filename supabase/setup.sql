create or replace function public.audit_offer_changes()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_offer_id uuid;
  v_details jsonb;
  v_action text := lower(tg_op);
begin
  if tg_op = 'DELETE' then
    v_offer_id := old.id;
    v_details := jsonb_build_object('before',to_jsonb(old));
  elsif tg_op = 'UPDATE' then
    v_offer_id := new.id;
    v_details := jsonb_build_object('before',to_jsonb(old),'after',to_jsonb(new));
  else
    v_offer_id := new.id;
    v_details := jsonb_build_object('after',to_jsonb(new));
  end if;
  insert into public.offer_audit_events(actor_id,action,offer_id,details)
  values(auth.uid(),'offer_'||v_action,v_offer_id,v_details);
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;
